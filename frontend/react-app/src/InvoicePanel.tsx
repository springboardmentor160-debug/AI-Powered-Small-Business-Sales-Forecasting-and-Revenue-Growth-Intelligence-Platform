import { useCallback, useEffect, useMemo, useRef, useState, type FormEvent } from "react";
import { AlertCircle, Check, ChevronDown, Download, FileText, Plus, RefreshCw, Search, X } from "lucide-react";
import CountUp from "./CountUp";
import { SkeletonRows } from "./Skeleton";
import {
  ApiRequestError, createInvoice, getInvoices,
  type InvoiceListResponse, type InvoiceRecord, type PaymentStatus, type UserRole,
} from "./lib/api";

interface InvoicePanelProps { token: string; role: UserRole }

const STATUSES: PaymentStatus[] = ["Pending", "Paid", "Cancelled"];
const TEMPLATES: { id: string; title: string; hint: string; status: PaymentStatus }[] = [
  { id: "standard", title: "Standard invoice", hint: "Payment pending", status: "Pending" },
  { id: "receipt", title: "Paid receipt", hint: "Already settled", status: "Paid" },
  { id: "blank", title: "Blank invoice", hint: "Start from scratch", status: "Pending" },
];

const money = (v: number) => Number(v).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const esc = (v: unknown) => String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

function downloadInvoice(inv: InvoiceRecord) {
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(inv.invoice_id)}</title>
<style>body{font-family:Inter,Arial,sans-serif;color:#1A2233;max-width:720px;margin:48px auto;padding:0 24px}
h1{font-family:Georgia,serif;margin:0;color:#003B46}.gold{color:#006770;letter-spacing:.25em;font-size:11px;font-weight:700}
.head{display:flex;justify-content:space-between;border-bottom:2px solid #00A3A9;padding-bottom:18px;margin-bottom:28px}
table{width:100%;border-collapse:collapse}th{background:#003B46;color:#BFF2F4;text-align:left;padding:10px;font-size:11px;letter-spacing:.12em;text-transform:uppercase}
td{padding:12px 10px;border-bottom:1px solid #CFE5E7}.r{text-align:right}.tot{font-size:20px;font-weight:700;color:#003B46}
.meta td{border:0;padding:4px 0}.badge{display:inline-block;padding:3px 12px;border-radius:99px;border:1px solid #00A3A9;background:#E6F7F8;font-size:12px;font-weight:700}
.foot{margin-top:40px;font-size:11px;color:#6B7385}@media print{body{margin:0}}</style></head><body>
<div class="head"><div><div class="gold">MARKETMIND AI</div><h1>Invoice</h1></div><div class="r"><b>${esc(inv.invoice_id)}</b><br>${esc(new Date(inv.created_at).toLocaleString())}<br><span class="badge">${esc(inv.payment_status)}</span></div></div>
<table class="meta"><tr><td><b>Billed to</b></td><td>${esc(inv.customer_name)}</td></tr><tr><td><b>Issued by</b></td><td>${esc(inv.created_by)}</td></tr></table><br>
<table><thead><tr><th>Product</th><th class="r">Qty</th><th class="r">Unit price</th><th class="r">Amount</th></tr></thead>
<tbody><tr><td>${esc(inv.product_name)}</td><td class="r">${esc(inv.quantity)}</td><td class="r">${money(inv.unit_price)}</td><td class="r">${money(inv.total_amount)}</td></tr></tbody></table>
<p class="r tot">Total: ${money(inv.total_amount)}</p>
<p class="foot">Generated by MarketMind AI Business Intelligence. Open this file and use Print → Save as PDF for a PDF copy.</p></body></html>`;
  const url = URL.createObjectURL(new Blob([html], { type: "text/html;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url; a.download = `${inv.invoice_id}.html`; a.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export default function InvoicePanel({ token, role }: InvoicePanelProps) {
  const [data, setData] = useState<InvoiceListResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState("");
  const [formError, setFormError] = useState("");
  const [toast, setToast] = useState("");
  const [menuOpen, setMenuOpen] = useState(false);
  const [modal, setModal] = useState<string | null>(null);
  const [query, setQuery] = useState("");
  const [filter, setFilter] = useState<"All" | PaymentStatus>("All");
  const menuRef = useRef<HTMLDivElement>(null);

  const [customerName, setCustomerName] = useState("");
  const [productName, setProductName] = useState("");
  const [quantity, setQuantity] = useState("1");
  const [unitPrice, setUnitPrice] = useState("1.00");
  const [paymentStatus, setPaymentStatus] = useState<PaymentStatus>("Pending");

  const canCreate = role === "sales_executive" || role === "admin";

  const load = useCallback(async () => {
    setLoading(true); setError("");
    try { setData(await getInvoices(token)); }
    catch (e: unknown) { setError(e instanceof ApiRequestError ? e.message : "Unable to load invoices."); }
    finally { setLoading(false); }
  }, [token]);

  useEffect(() => { void Promise.resolve().then(() => void load()); }, [load]);
  useEffect(() => {
    if (!toast) return;
    const t = window.setTimeout(() => setToast(""), 3000);
    return () => window.clearTimeout(t);
  }, [toast]);
  useEffect(() => {
    const onDoc = (e: MouseEvent) => { if (menuRef.current && !menuRef.current.contains(e.target as Node)) setMenuOpen(false); };
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") { setMenuOpen(false); setModal(null); } };
    document.addEventListener("mousedown", onDoc); window.addEventListener("keydown", onKey);
    return () => { document.removeEventListener("mousedown", onDoc); window.removeEventListener("keydown", onKey); };
  }, []);

  function openTemplate(id: string) {
    const t = TEMPLATES.find((x) => x.id === id)!;
    setCustomerName(""); setProductName(""); setQuantity("1"); setUnitPrice("1.00");
    setPaymentStatus(t.status); setFormError(""); setMenuOpen(false); setModal(t.title);
  }

  async function handleCreate(e: FormEvent) {
    e.preventDefault(); setFormError("");
    const q = Number(quantity), p = Number(unitPrice);
    if (!customerName.trim() || !productName.trim()) return setFormError("Customer and product are required.");
    if (!Number.isInteger(q) || q < 1 || q > 1_000_000) return setFormError("Quantity must be a whole number between 1 and 1,000,000.");
    if (!Number.isFinite(p) || p <= 0 || p > 100_000_000) return setFormError("Unit price must be greater than 0.");
    setSaving(true);
    try {
      const r = await createInvoice({ customer_name: customerName.trim(), product_name: productName.trim(), quantity: q, unit_price: p, payment_status: paymentStatus }, token);
      setModal(null); setToast(`Invoice ${r.invoice.invoice_id} created`); await load();
    } catch (err: unknown) { setFormError(err instanceof ApiRequestError ? err.message : "Unable to create the invoice."); }
    finally { setSaving(false); }
  }

  function exportCsv() {
    if (!data) return;
    const cols = ["invoice_id", "customer_name", "product_name", "quantity", "unit_price", "total_amount", "payment_status", "created_by", "created_at"] as const;
    const q = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;
    const rows = [cols.join(","), ...data.invoices.map((i) => cols.map((c) => q(i[c])).join(","))];
    const url = URL.createObjectURL(new Blob(["\uFEFF", rows.join("\r\n")], { type: "text/csv;charset=utf-8;" }));
    const a = document.createElement("a"); a.href = url; a.download = "marketmind-invoices.csv"; a.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  const invoices = data?.invoices ?? [];
  const shown = useMemo(() => {
    const s = query.toLowerCase().trim();
    return invoices.filter((i) => (filter === "All" || i.payment_status === filter) &&
      (!s || `${i.invoice_id} ${i.customer_name} ${i.product_name}`.toLowerCase().includes(s)));
  }, [invoices, query, filter]);
  const sum = (st?: PaymentStatus) => invoices.filter((i) => !st || i.payment_status === st).reduce((a, i) => a + Number(i.total_amount), 0);
  const total = Math.max(0, Number(quantity) || 0) * Math.max(0, Number(unitPrice) || 0);

  return (
    <section className="invoice-panel lx-page">
      <div className="section-heading">
        <div>
          <p className="eyebrow">TRANSACTION MANAGEMENT</p>
          <h2><FileText size={22} /> Invoice registry</h2>
        </div>
        <div className="inventory-actions">
          <button type="button" className="button button-secondary" onClick={() => void load()} disabled={loading}>
            <RefreshCw size={16} className={loading ? "lx-spin" : ""} /> Refresh
          </button>
          <button type="button" className="button button-secondary" onClick={exportCsv} disabled={!data || loading}>
            <Download size={16} /> Export CSV
          </button>
          {canCreate && (
            <div className="lx-menu" ref={menuRef}>
              <button type="button" className="button button-primary" aria-haspopup="menu" aria-expanded={menuOpen} onClick={() => setMenuOpen((o) => !o)}>
                <Plus size={16} /> Create New Invoice <ChevronDown size={16} className={menuOpen ? "lx-flip" : ""} />
              </button>
              {menuOpen && (
                <div className="lx-dropdown" role="menu">
                  {TEMPLATES.map((t) => (
                    <button key={t.id} type="button" role="menuitem" onClick={() => openTemplate(t.id)}>
                      <b>{t.title}</b><small>{t.hint}</small>
                    </button>
                  ))}
                </div>
              )}
            </div>
          )}
        </div>
      </div>

      {!canCreate && <p className="invoice-readonly">Your role has read-only access to the invoice registry.</p>}
      {error && <p className="invoice-error" role="alert"><AlertCircle size={17} /> {error} <button type="button" className="lx-retry" onClick={() => void load()}>Retry</button></p>}

      <div className="lx-stats">
        {[["Total billed", sum()], ["Collected", sum("Paid")], ["Outstanding", sum("Pending")]].map(([t, v], i) => (
          <article key={String(t)} className="lx-stat" style={{ animationDelay: `${i * 80}ms` }}><span>{String(t)}</span><strong><CountUp value={Number(v)} decimals={2} /></strong></article>
        ))}
      </div>

      <div className="lx-toolbar">
        <label className="lx-search"><Search size={16} />
          <input placeholder="Search invoice, customer or product…" value={query} onChange={(e) => setQuery(e.target.value)} />
        </label>
        <div className="lx-chips">
          {(["All", ...STATUSES] as const).map((s) => (
            <button key={s} type="button" className={filter === s ? "on" : ""} onClick={() => setFilter(s)}>{s}</button>
          ))}
        </div>
      </div>

      <div className="forecast-table-wrap">
        <table className="forecast-table invoice-table lx-table">
          <thead><tr><th>Invoice ID</th><th>Customer</th><th>Product</th><th>Qty</th><th>Unit price</th><th>Total</th><th>Status</th><th>Created by</th><th>Created at</th><th className="lx-right">Actions</th></tr></thead>
          <tbody>
            {loading && !data && <SkeletonRows cols={10} />}
            {shown.map((i, n) => (
              <tr key={i.invoice_id} className="lx-row" style={{ animationDelay: `${Math.min(n, 12) * 40}ms` }}>
                <td><b>{i.invoice_id}</b></td><td>{i.customer_name}</td><td>{i.product_name}</td>
                <td>{i.quantity.toLocaleString()}</td><td>{money(i.unit_price)}</td><td><b>{money(i.total_amount)}</b></td>
                <td><span className={`lx-badge ${i.payment_status.toLowerCase()}`}>{i.payment_status}</span></td>
                <td>{i.created_by}</td><td>{new Date(i.created_at).toLocaleString()}</td>
                <td className="lx-right"><button type="button" className="lx-btn gold" onClick={() => { downloadInvoice(i); setToast(`${i.invoice_id} downloaded`); }}><Download size={14} /> Download</button></td>
              </tr>
            ))}
            {!loading && shown.length === 0 && <tr><td colSpan={10}>No invoices match.</td></tr>}
          </tbody>
        </table>
      </div>

      {modal && (
        <div className="lx-overlay" onClick={() => setModal(null)}>
          <form className="lx-modal" onClick={(e) => e.stopPropagation()} onSubmit={handleCreate}>
            <div className="lx-modal-head"><h3>New {modal.toLowerCase()}</h3>
              <button type="button" className="lx-x" onClick={() => setModal(null)} aria-label="Close"><X size={18} /></button></div>
            <label>Customer name<input autoFocus value={customerName} maxLength={150} onChange={(e) => setCustomerName(e.target.value)} /></label>
            <label>Product name<input value={productName} maxLength={200} onChange={(e) => setProductName(e.target.value)} /></label>
            <div className="lx-two">
              <label>Quantity<input type="number" min={1} step={1} value={quantity} onChange={(e) => setQuantity(e.target.value)} /></label>
              <label>Unit price<input type="number" min="0.01" step="0.01" value={unitPrice} onChange={(e) => setUnitPrice(e.target.value)} /></label>
            </div>
            <label>Payment status<select value={paymentStatus} onChange={(e) => setPaymentStatus(e.target.value as PaymentStatus)}>
              {STATUSES.map((s) => <option key={s}>{s}</option>)}</select></label>
            <p className="lx-total">Total <b>{money(total)}</b></p>
            {formError && <p className="lx-form-error"><AlertCircle size={15} /> {formError}</p>}
            <div className="lx-modal-foot">
              <button type="button" className="button button-secondary" onClick={() => setModal(null)}>Cancel</button>
              <button type="submit" className="button button-primary" disabled={saving}>{saving ? "Saving…" : "Create invoice"}</button>
            </div>
          </form>
        </div>
      )}

      {toast && <div className="lx-toast" role="status"><Check size={16} /> {toast}</div>}
    </section>
  );
}
